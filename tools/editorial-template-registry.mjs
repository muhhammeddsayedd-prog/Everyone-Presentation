// Pins every byte the Everyone Film editorial template 1.2.0 renders with.
// `node tools/editorial-template-registry.mjs` rewrites the registry;
// `--check` exits non-zero when any pinned file changed without re-registration.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = 'packages/templates/versions/1.2.0/registry.json';
const RENDERER_FILES = ['tokens.ts', 'deck.ts', 'layouts.ts', 'compose-casting.ts', 'html.ts', 'render.ts', 'pptx.ts', 'static-images.ts'].map(file => `packages/templates/versions/1.2.0/${file}`);
const STATIC_IMAGES = { everyone_wordmark: 'apps/web/public/brand/everyone-logotype.svg', casting_placeholder: 'apps/web/public/templates/everyone-film/casting-placeholder.png', everyone_wordmark_raster: 'apps/web/public/templates/everyone-film/everyone-wordmark.png' };
const LATIN = [[200, 'Extralight'], [300, 'Light'], [400, 'Regular'], [500, 'Medium'], [600, 'Semibold'], [700, 'Bold']];
const ARABIC = [[400, 'Regular'], [500, 'Medium'], [600, 'SemiBold']];
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const canonical = value => Array.isArray(value) ? `[${value.map(canonical).join(',')}]`
  : value && typeof value === 'object' ? `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}` : JSON.stringify(value);
const pin = async file => { const bytes = await readFile(path.join(ROOT, file)); return { path: file, sha256: sha(bytes), bytes: bytes.byteLength }; };

// PowerPoint export runs in a serverless handler: embed the two pinned raster
// images as a generated module instead of reading public files at runtime.
const STATIC_MODULE = 'packages/templates/versions/1.2.0/static-images.ts';
const raster = async file => `data:image/png;base64,${(await readFile(path.join(ROOT, file))).toString('base64')}`;
const staticModule = `// Generated by tools/editorial-template-registry.mjs from pinned public files. Do not edit.
export const PPTX_STATIC_IMAGES = {
  everyone_wordmark: { data: '${await raster(STATIC_IMAGES.everyone_wordmark_raster)}', natural: [1450, 242] as const },
  casting_placeholder: { data: '${await raster(STATIC_IMAGES.casting_placeholder)}', natural: [1038, 1038] as const },
};
`;
if (process.argv.includes('--check')) { if ((await readFile(path.join(ROOT, STATIC_MODULE), 'utf8').catch(() => '')) !== staticModule) { console.error(`${STATIC_MODULE} is stale`); process.exit(1); } }
else await writeFile(path.join(ROOT, STATIC_MODULE), staticModule);
const body = {
  key: 'everyone-casting', version: '1.2.0', design_system: 'everyone-film-editorial-presentation', design_spec: 'everyone_template_design_kit/design.md v1.0',
  font_key: 'everyone-film-fonts-v1', width: 1920, height: 1080, renderer_version: 'everyone-film-html-v1',
  renderer_files: await Promise.all(RENDERER_FILES.map(pin)),
  static_images: Object.fromEntries(await Promise.all(Object.entries(STATIC_IMAGES).map(async ([key, file]) => [key, await pin(file)]))),
  fonts: [
    ...await Promise.all(LATIN.map(async ([weight, name]) => ({ ...await pin(`apps/web/public/fonts/GeneralSans-${name}.ttf`), family: 'Latin', weight, source: 'Fontshare official General Sans package (GeneralSans_Complete/Fonts/WEB/fonts TrueType), unmodified' }))),
    ...await Promise.all(ARABIC.map(async ([weight, name]) => ({ ...await pin(`apps/web/public/fonts/IBMPlexSansArabic-${name}.woff2`), family: 'Arabic', weight, source: 'ibm-plex-sans-arabic-1.1.0.tgz, unmodified' }))),
  ],
  font_license: 'General Sans: ITF Free Font License 2.0 (apps/web/public/fonts/GeneralSans-LICENSE.txt) — self-hosted in this private application and embedded in its PDFs; files are unmodified and must not be redistributed. IBM Plex Sans Arabic: SIL OFL 1.1.',
  font_substitution: 'Geeza Pro (source Arabic dialogue face) is an Apple system font that cannot be bundled; IBM Plex Sans Arabic is the declared Arabic fallback. Latin text uses the source General Sans faces.',
};
const registry = { ...body, content_sha256: sha(canonical(body)) };
const target = path.join(ROOT, REGISTRY); const next = `${JSON.stringify(registry, null, 2)}\n`;
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== next) { console.error(`${REGISTRY} is stale: run node tools/editorial-template-registry.mjs`); process.exit(1); }
  console.log(`${REGISTRY} current (${registry.content_sha256})`);
} else { await writeFile(target, next); console.log(`${REGISTRY} → ${registry.content_sha256}`); }
